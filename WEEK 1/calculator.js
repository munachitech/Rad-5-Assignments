function add(a, b) {

    return a + b;

}



function subtract(a, b) {

    return a - b;

}



function multiply(a, b) {

    return a * b;

}



function divide(a, b) {

    return a / b;

}



console.log("Addition:", add(20, 10));

console.log("Subtraction:", subtract(20, 10));

console.log("Multiplication:", multiply(20, 10));

console.log("Division:", divide(20, 10));